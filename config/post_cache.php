<?php

return [
    /*
    |--------------------------------------------------------------------------
    | 文章緩存 TTL（Time To Live）
    |--------------------------------------------------------------------------
    |
    | 單一文章的緩存存活時間（秒）
    |
    | 建議設定：
    | - 30 分鐘  = 1800 秒  （適合更新頻繁的部落格）
    | - 1 小時   = 3600 秒  （平衡效能與即時性，推薦）
    | - 6 小時   = 21600 秒 （適合很少更新的內容）
    | - 24 小時  = 86400 秒 （適合靜態內容）
    |
    | 注意：
    | 1. 觀看次數不受緩存影響，會即時從 Redis 合併
    | 2. 文章更新/刪除/狀態變更時會自動清除緩存
    | 3. 留言數量會被緩存，新增留言時會自動清除緩存
    |
    */
    'ttl' => env('POST_CACHE_TTL', 3600), // 預設 1 小時

    /*
    |--------------------------------------------------------------------------
    | 緩存鍵前綴
    |--------------------------------------------------------------------------
    |
    | 用於區分不同類型的緩存，避免鍵名衝突
    |
    */
    'key_prefix' => env('POST_CACHE_KEY_PREFIX', 'post:published:'),
];
